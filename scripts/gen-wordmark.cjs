// Outlines the tamuko wordmark from Fredoka 700 using the exact layout of the brand guidelines
// (Brand.dc.html, "Wordmark only"): "tamuk" 96px, letter-spacing -1.2px, line-height 1, then a 3px gap
// and a column with a small "o" (83px, line-height .62) resting on a 38×11 peach bar 7px below.
// Output: src/brand/wordmark.ts (paths in a 96-unit design space). Run: node scripts/gen-wordmark.cjs
const fs = require('fs');
const path = require('path');
const opentype = require('opentype.js');

const font = opentype.loadSync(path.join(__dirname, '..', 'node_modules/@expo-google-fonts/fredoka/700Bold/Fredoka_700Bold.ttf'));
const upm = font.unitsPerEm;
const asc = font.tables.hhea.ascender / upm;
const desc = -font.tables.hhea.descender / upm;

const SIZE = 96, LS = -1.2, O_SIZE = 83, O_LH = 0.62, BAR_W = 38, BAR_H = 11, BAR_GAP = 7, GAP = 3, PAD_B = 2;
const LINE = SIZE; // line-height: 1
const baseTamuk = (LINE - (asc + desc) * SIZE) / 2 + asc * SIZE;

// "tamuk" glyph by glyph with letter-spacing
let x = 0;
let tamuk = '';
for (const ch of 'tamuk') {
  const g = font.charToGlyph(ch);
  tamuk += g.getPath(x, baseTamuk, SIZE).toPathData(2);
  x += (g.advanceWidth / upm) * SIZE + LS;
}
const oGlyph = font.charToGlyph('o');
const oAdv = (oGlyph.advanceWidth / upm) * O_SIZE;
const groupW = Math.max(oAdv + LS, BAR_W); // the o span inherits letter-spacing
const groupX = x + GAP;
const oBox = O_SIZE * O_LH;
const groupH = oBox + BAR_GAP + BAR_H;
const groupTop = LINE - groupH; // aligned to the bottom of the line (align-items: flex-end)
const oTop = groupTop + (oBox - (asc + desc) * O_SIZE) / 2;
const oBase = oTop + asc * O_SIZE;
const oX = groupX + (groupW - (oAdv + LS)) / 2;
const o = oGlyph.getPath(oX, oBase, O_SIZE).toPathData(2);
const bar = { x: +(groupX + (groupW - BAR_W) / 2).toFixed(2), y: +(groupTop + oBox + BAR_GAP).toFixed(2), w: BAR_W, h: BAR_H, r: BAR_H / 2 };
const width = +(groupX + groupW).toFixed(2);
const height = LINE + PAD_B;

const out = `// GENERATED by scripts/gen-wordmark.cjs — the tamuko wordmark outlined from Fredoka 700 (stand-in for Molen Friend)
// using the brand guidelines' layout. Design space: ${width} × ${height}.
export const WORDMARK = ${JSON.stringify({ width, height, tamuk, o, bar })} as const;
`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'brand', 'wordmark.ts'), out);
console.log({ width, height, baseTamuk: baseTamuk.toFixed(1), oBase: oBase.toFixed(1), bar });
